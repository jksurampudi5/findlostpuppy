/**
 * Returns strictly alphabetical (A-Z) list of Villages / Localities for a given Mandal.
 * If specific curated villages exist, returns them.
 * Otherwise dynamically creates sensible alphabetical locality/village options for that Mandal.
 */
export function getVillagesForMandal(
  _stateName: string,
  _districtName: string,
  mandalName: string
): string[] {
  if (!mandalName || mandalName === 'CUSTOM') return [];

  // Match against curated list
  const matchedKey = Object.keys(MANDAL_VILLAGES_DATA).find(
    (k) =>
      k.toLowerCase() === mandalName.trim().toLowerCase() ||
      mandalName.trim().toLowerCase().includes(k.toLowerCase()) ||
      k.toLowerCase().includes(mandalName.trim().toLowerCase())
  );

  if (matchedKey && MANDAL_VILLAGES_DATA[matchedKey]) {
    return [...MANDAL_VILLAGES_DATA[matchedKey]].sort((a, b) => a.localeCompare(b));
  }

  // Clean raw mandal name
  const cleanName = mandalName.replace(/\s*\([^)]*\)/g, '').trim();

  // Algorithmic default village list for any other mandal
  const generated = [
    cleanName,
    `${cleanName} Central`,
    `${cleanName} Colony`,
    `${cleanName} East`,
    `${cleanName} Market`,
    `${cleanName} Rural`,
    `${cleanName} West`,
  ];

  return generated.sort((a, b) => a.localeCompare(b));
}


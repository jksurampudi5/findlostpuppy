/**
 * Returns strictly alphabetical (A-Z) list of districts for a given state.
 */
export function getDistrictsForState(stateName: string): string[] {
  const matchedKey = SUPPORTED_STATES.find(
    (s) => s.toLowerCase() === stateName.trim().toLowerCase()
  );
  const stateData = (matchedKey && REGIONAL_GEO_DATA[matchedKey])
    ? REGIONAL_GEO_DATA[matchedKey]
    : REGIONAL_GEO_DATA['Andhra Pradesh'];

  return Object.keys(stateData).sort((a, b) => a.localeCompare(b));
}

/**
 * Returns strictly alphabetical (A-Z) list of mandals for a given state & district.
 */
export function getMandalsForDistrict(stateName: string, districtName: string): string[] {
  const matchedState = SUPPORTED_STATES.find(
    (s) => s.toLowerCase() === stateName.trim().toLowerCase()
  );
  if (matchedState && REGIONAL_GEO_DATA[matchedState]) {
    const districts = REGIONAL_GEO_DATA[matchedState];
    const matchedDistKey = Object.keys(districts).find(
      (d) =>
        d.toLowerCase() === districtName.trim().toLowerCase() ||
        d.toLowerCase().includes(districtName.trim().toLowerCase()) ||
        districtName.trim().toLowerCase().includes(d.toLowerCase())
    );
    if (matchedDistKey && districts[matchedDistKey]) {
      return [...districts[matchedDistKey]].sort((a, b) => a.localeCompare(b));
    }
  }
  return [];
}

/**
 * Matches detected state string to supported states, falling back to 'Andhra Pradesh'.
 */
export function normalizeSupportedState(rawState: string): SupportedState {
  const lower = rawState.trim().toLowerCase();
  if (lower.includes('telangana')) return 'Telangana';
  if (lower.includes('karnataka')) return 'Karnataka';
  return 'Andhra Pradesh';
}

